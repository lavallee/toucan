// Writes app/preflight.css: Tailwind's preflight wrapped in `@scope (.toucan-ui)`, so the reset
// only applies to our shadcn UI (chat panel, badge, sign-in) and never to tldraw's canvas or UI.
// Re-run after upgrading tailwindcss: `npm run css:preflight`.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const src = require.resolve('tailwindcss/preflight.css')
const { version } = require('tailwindcss/package.json')
let css = readFileSync(src, 'utf8')

// The document-level rule becomes the scope root.
const root = /^html,\n:host \{/m
if (!root.test(css)) throw new Error('preflight.css changed shape: no `html, :host {` rule')
css = css.replace(root, ':scope {')

const out = `/* GENERATED by scripts/scope-preflight.mjs from tailwindcss@${version} preflight.css. Do not edit. */
@scope (.toucan-ui) {
${css.replace(/^(?=.)/gm, '  ')}}
`
writeFileSync(fileURLToPath(new URL('../app/preflight.css', import.meta.url)), out)
console.log(`app/preflight.css <- tailwindcss@${version}`)
